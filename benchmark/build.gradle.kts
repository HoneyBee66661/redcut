// :benchmark — the baseline profile generator (spec §11 "Baseline Profiles", task 0.6).
//
// A profile is a claim about which code paths matter on a cold start and a first
// interaction, and a claim nobody measures is a guess. This module is the measurement:
// a `com.android.test` module that instruments a real device, drives the app, and writes
// the paths it touched into `src/main/baselineProfiles`.
//
// WHY A SEPARATE MODULE AND NOT A TEST SOURCE SET
//
// A `com.android.test` module owns its own instrumentation APK and declares which app it
// runs against (`targetProjectPath`). That direction is one-way — this module depends on
// :app and :app never depends on it — so the generator cannot end up in the product, and
// the benchmark dependency (a large instrumentation stack) cannot end up in the APK.
//
// WHY IT IS NOT PART OF PR CI
//
// Generation needs a booted device and several minutes of it. PR CI does not have one
// (no KVM-guaranteed emulator, no time budget), so the profile is generated by
// .github/workflows/baseline-profile.yml — on demand, weekly, and when this module or
// the shipped profile changes. Everything a PR can check about it locally is that the
// module CONFIGURES (it is part of the build) and that the generator compiles (the
// quality job).
plugins {
    alias(libs.plugins.android.test)
    alias(libs.plugins.kotlin.android)
    // The `androidx.baselineprofile` plugin is applied on both sides of the profile: on
    // :app it turns generated rules into a shipped asset, and here it creates the
    // `benchmarkRelease`-style variant and the `collect*BaselineProfile` tasks that run
    // this test against the instrumented app.
    alias(libs.plugins.androidx.baselineprofile)
}

android {
    namespace = "com.redcut.benchmark"

    // Read from the catalog rather than written here: a second place where compileSdk
    // is spelled is a second place that can be missed on an SDK bump (see the version
    // policy note at the top of gradle/libs.versions.toml).
    compileSdk = libs.versions.compileSdk.get().toInt()

    defaultConfig {
        minSdk = libs.versions.minSdk.get().toInt()
        targetSdk = libs.versions.targetSdk.get().toInt()
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    // The app under test. Naming it here is what keeps the generator from drifting away
    // from the app it profiles: this module cannot be pointed at a different project
    // without editing this line.
    targetProjectPath = ":app"

    // The generator is its own instrumentation target. Without this, AGP looks for a
    // second module to own the instrumentation APK and the build fails at configuration.
    experimentalProperties["android.experimental.self-instrumenting"] = true

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    // NOTE the deliberate absence of a `buildTypes` block: the profile plugin creates the
    // variants it needs (a non-minified release of the target app, a matching variant
    // here) and copies the app's signing config where it must. Declaring a `benchmark`
    // build type by hand as well is what a template does; it is also the thing most
    // likely to collide with the plugin's own variant creation on a future AGP bump.
}

/**
 * Where the profile comes from.
 *
 * `useConnectedDevices = true` is the honest description of this project's only device:
 * the emulator that the `baseline-profile` workflow boots and attaches over adb. Gradle
 * Managed Devices are the other supported source and are not available on a hosted
 * runner, so leaving this to a default would mean a run that silently generates from
 * nothing.
 *
 * `skipBenchmarksOnEmulator = false` because there are no microbenchmarks to skip here —
 * this module generates a profile, it does not measure — and a profile generated on an
 * emulator is a valid profile: ART profiles record dex paths, not timings, and the
 * emulator's ABI does not enter into it. Timings are what an emulator could not be
 * trusted for, which is exactly why no benchmark lives in this module.
 */
baselineProfile {
    useConnectedDevices = true
    skipBenchmarksOnEmulator = false
}

dependencies {
    // The rule that drives the app and collects the profile.
    implementation(libs.androidx.benchmark.macro.junit4)
    implementation(libs.androidx.test.junit)
    // UI automation: the generator's job is to REACH the interesting screens (a cold
    // start alone would profile a splash and nothing else), and on this app every screen
    // is Compose, so reaching them means driving the UI rather than the test hooks.
    implementation(libs.androidx.test.uiautomator)
}
